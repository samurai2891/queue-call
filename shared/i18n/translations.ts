export function t(locale: Locale, key: TranslationKey | string): string {
  const trans = translations[locale] as Record<string, string>;
  const fallback = translations.ja as Record<string, string>;
  return trans?.[key] || fallback[key] || key;
}

export function detectLocale(): Locale {
  if (typeof navigator === 'undefined') return 'ja';
  
  const browserLang = navigator.language || (navigator as any).userLanguage || 'ja';
  const lang = browserLang.toLowerCase();
  
  if (lang.startsWith('ja')) return 'ja';
  if (lang.startsWith('ko')) return 'ko';
  if (lang === 'zh-tw' || lang === 'zh-hant' || lang === 'zh-hk') return 'zh-Hant';
  if (lang.startsWith('zh')) return 'zh-Hans';
  if (lang.startsWith('en')) return 'en';
  
  return 'ja';
}

export function getLocalizedField<T extends Record<string, any>>(
  item: T,
  fieldPrefix: string,
  locale: Locale
): string {
  const localeMap: Record<Locale, string> = {
    'ja': 'Ja',
    'en': 'En',
    'ko': 'Ko',
    'zh-Hans': 'ZhHans',
    'zh-Hant': 'ZhHant',
  };
  
  const suffix = localeMap[locale];
  const fieldName = `${fieldPrefix}${suffix}`;
  
  // Try requested locale first
  if (item[fieldName]) return item[fieldName];
  
  // Fallback to Japanese
  if (item[`${fieldPrefix}Ja`]) return item[`${fieldPrefix}Ja`];
  
  // Fallback to English
  if (item[`${fieldPrefix}En`]) return item[`${fieldPrefix}En`];
  
  return '';
}
